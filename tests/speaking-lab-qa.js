'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const D=require('../lara/speaking-lab-content.js'),C=require('../lara/speaking-lab-core.js');
let n=0;function ok(a,label){assert.ok(a,label);n++}
ok(D.version==='speaking-lab-1.0','versioned independent original content');
ok(D.official===false,'not represented as a national exam');
ok(D.topics.length>=48,'broad original topic bank');
ok(new Set(D.topics.map(t=>t.id)).size===D.topics.length,'unique topics');
ok(D.categories.length>=6,'varied topics');
for(const t of D.topics){
 ok(t.id.length>=2&&/^[a-z]+$/.test(t.id),'safe id '+t.id);
 ok(D.categories.some(c=>c.id===t.category),'known category '+t.id);
 ok(t.prompt.length>25&&t.prompt.endsWith('?'),'meaningful original question '+t.id);
 ok(t.follow.length>15&&t.follow.endsWith('?'),'topic-relevant follow-up '+t.id);
}
for(const t of ['crime','moneychoice','fair','climate','schoolrules','ai','friends'])ok(D.topics.some(x=>x.id===t),'required diverse topic '+t);
ok(D.framework.length===4,'PACE four actionable steps');
ok(D.framework.map(x=>x.label).join('')==='PositionReasonExampleEngage','PACE in order');
for(const r of D.rescue)ok(r.lines.length>=4,'graded rescue '+r.id);
for(const id of ['blank','bored','excited','word','disagree'])ok(D.rescue.some(r=>r.id===id),'critical rescue '+id);
ok(D.checks.length===6,'self-check covers content, relevance, interaction and language repair');
const clean=C.make({mode:'pair',seed:'fixed'});
ok(clean.deck.length===D.topics.length,'full surprise deck');
ok(new Set(clean.deck).size===clean.deck.length,'no repeats within deck');
ok(JSON.stringify(C.make({mode:'pair',seed:'fixed'}).deck)===JSON.stringify(clean.deck),'deterministic seeded deck');
ok(C.participants('solo')===1&&C.participants('pair')===2&&C.participants('group')===4,'three practice variants');
ok(C.card(clean).prompt===D.topics.find(x=>x.id===clean.deck[0]).prompt,'visible real prompt');
ok(C.follow(clean).length>10,'follow up shown');
let s=C.advance(clean);ok(s.stage==='reflect','speaking -> reflection');
s=C.advance(s);ok(s.stage==='card'&&s.turn===1,'pair has a responding speaker on the same card');
s=C.advance(s);s=C.advance(s);ok(s.stage==='review'&&s.rounds===1,'both speakers reviewed, not prematurely advanced');
const former=s.deck[s.index];s=C.advance(s);ok(s.stage==='card'&&s.index===1&&C.card(s).id!==former,'new surprise card');
let g=C.make({mode:'group',seed:'group'});for(let i=0;i<3;i++){g=C.advance(C.advance(g));ok(g.turn===i+1,'group turn '+i);}g=C.advance(C.advance(g));ok(g.stage==='review','group completes after everyone speaks');
const solo=C.make({mode:'solo',seed:'solo'});ok(C.advance(C.advance(solo)).stage==='review','solo completion');
const q=C.make({category:'money',seed:'private'});ok(q.deck.every(id=>D.topics.find(x=>x.id===id).category==='money'),'category selection scoped');
ok(C.safe({...clean,deck:['fake']})===null,'reject malicious session deck');
ok(C.safe({...clean,mode:'group',turn:9})===null,'reject out-of-range turn');
ok(C.safe({...clean,index:999})===null,'reject out-of-range index');
ok(C.make({mode:'other',category:'unknown'}).mode==='solo','sanitize unknown controls');
const fakeStorage={values:{},getItem(k){return this.values[k]},setItem(k,v){this.values[k]=v},removeItem(k){delete this.values[k]}};
ok(C.save(fakeStorage,s),'save only synthetic state');
ok(!!C.load(fakeStorage)&&C.load(fakeStorage).index===s.index,'restore session');
ok(!JSON.stringify(fakeStorage).includes('answer'),'session does not save a voice transcript');
ok(C.clear(fakeStorage)&&C.load(fakeStorage)===null,'clear session');
const feedback=C.insights(['clear','reason','listen']);
ok(feedback.count===3&&feedback.nextTip.length>5,'honest feedback without automatic grade');
const html=fs.readFileSync('lara/speaking-lab.html','utf8'),app=fs.readFileSync('lara/speaking-lab.js','utf8');
for(const name of ['speaking-lab-content.js','speaking-lab-core.js','speaking-lab.js','speaking-lab.css'])ok(html.includes(name),'assets linked '+name);
ok(!/getUserMedia|MediaRecorder|webkitSpeechRecognition|SpeechRecognition/.test(app),'no microphone or recording');
ok(!/fetch\(|XMLHttpRequest|sendBeacon/.test(app),'no remote pupil data transfer');
ok(app.includes('ingen mikrofon')||app.includes('Ingen mikrofon'),'students get a clear privacy statement');
ok(app.includes('ingen automatisk')||app.includes('inga automatiska'),'no automatic grading claim');
console.log('SPEAKING LAB STATIC QA '+n+'/'+n+' PASS ('+D.topics.length+' original cards)');
