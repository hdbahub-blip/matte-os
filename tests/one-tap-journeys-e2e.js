/* Matte OS FULLSPEC end-to-end journey acceptance.
   Synthetic, isolated browser storage; never creates cloud accounts or external rooms. */
'use strict';
const assert = require('node:assert/strict');
const {chromium,webkit} = require('playwright');
const fs = require('node:fs');
const BASE=(process.argv[2]||'http://127.0.0.1:8765/').replace(/\/?$/,'/');
const engine=process.argv[3]==='webkit'?'webkit':'chromium';
(async()=>{
  const browser=await (engine==='webkit'?webkit:chromium).launch({headless:true});
  let checks=0;
  try{
    const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2,serviceWorkers:'block'});
    const page=await context.newPage();
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    page.on('dialog',d=>d.accept().catch(()=>{}));
    page.setDefaultTimeout(16000);
    await page.goto(BASE,{waitUntil:'load'});
    await page.locator('.pc-onboarding .pc-grade9').click();
    await page.locator('.ux-landing').waitFor();
    assert.equal(await page.locator('.ux-tiles .ux-tile').count(),4);checks++;
    assert.equal(await page.locator('.ux-tiles a[href^="lara/"]').count(),2);checks++;
    assert.equal(await page.locator('.ux-more').getAttribute('open'),null);checks++;
    assert.equal(await page.locator('.ux-play').getAttribute('href'),'tillsammans/?start=group&grade=grade9');checks++;
    await page.evaluate(()=>{
      const x=window.MOEngine.state();
      x.profiles.grade9.rests.auditSentinel='grade9-safe';
      x.profiles.grade8.rests.auditSentinel='grade8-safe';
      window.MOEngine.save();
      localStorage.setItem('matteos.larande.v1','{"audit":"learning-safe"}');
    });
    await page.locator('.ux-math').click();
    await page.waitForURL(/#\/run/);
    assert.match(await page.locator('.fbar .ttl').innerText(),/Blandträning|Träna/);checks++;
    assert.equal(await page.evaluate(()=>window.MOEngine.state().active),'grade9');checks++;
    await page.goto(BASE,{waitUntil:'load'});
    await page.locator('.ux-play').click();
    await page.locator('h1').filter({hasText:'Redo att köra ihop?'}).waitFor();checks++;
    assert.equal(await page.locator('input[data-role=participant]:checked').count(),2);checks++;
    await page.locator('#topic').selectOption('table');
    await page.locator('.flow-extra-content summary').first().click();
    await page.locator('select[data-role=source]').selectOption('table:7:v1');
    const participants=page.locator('input[data-role=participant]');
    const ids=await participants.evaluateAll(xs=>xs.map(x=>x.value));
    assert(ids.includes('grade8')&&ids.includes('grade9'));checks++;
    const checked=await participants.evaluateAll(xs=>xs.filter(x=>x.checked).map(x=>x.value));
    assert.equal(checked.length,2);checks++;
    await page.locator('input[data-role=participant][value="'+checked[0]+'"]').uncheck();
    await page.locator('input[data-role=participant][value="'+checked[1]+'"]').uncheck();
    await page.locator('input[data-role=participant][value="grade8"]').check();
    await page.locator('input[data-role=participant][value="grade9"]').check();
    assert.match(await page.locator('.flow-players-head span').innerText(),/^2 valda/);checks++;
    assert.match(await page.locator('[data-action=start-session]').innerText(),/2 personer/);checks++;
    const prefs=await page.evaluate(()=>JSON.parse(localStorage.getItem('matteos.together.flow.v1')));
    assert.equal(prefs.topic,'table');checks++;
    assert.equal(prefs.ref,'table:7:v1');checks++;
    assert.equal(prefs.members.length,2);checks++;
    await page.locator('[data-action=start-session]').click();
    assert.match(await page.locator('main').innerText(),/Fråga 1 av 5/);checks++;
    let session=await page.evaluate(()=>window.MOTogether.restoreSession());
    assert.equal(session.members.length,2);checks++;
    assert.equal(session.count,5);checks++;
    assert.equal(session.phase,'handoff');checks++;
    await page.locator('[data-action=begin-turn]').click();
    assert.equal(await page.locator('.options [data-action=choose]').count()>1,true);checks++;
    await page.locator('.options [data-action=choose]').first().click();
    await page.locator('[data-action=submit-turn]').click();
    session=await page.evaluate(()=>window.MOTogether.restoreSession());
    assert.equal(session.phase,'handoff');checks++;
    await page.locator('[data-action=begin-turn]').click();
    await page.locator('.options [data-action=choose]').first().click();
    await page.locator('[data-action=submit-turn]').click();
    assert.match(await page.locator('main').innerText(),/ALLA HAR SVARAT/);checks++;
    await page.locator('[data-action=next-round]').click();
    assert.match(await page.locator('main').innerText(),/Fråga 2 av 5/);checks++;
    await page.reload({waitUntil:'load'});
    assert.equal(await page.locator('[data-action=resume]').count(),1,'paused group is resumable, deep-link consumed');checks++;
    await page.locator('header a.logo').click();
    await page.locator('.ux-play').click();
    await page.locator('[data-action=resume]').waitFor();
    assert.equal(await page.locator('h1').filter({hasText:'Redo att köra ihop?'}).count(),0,'return shortcut honors paused group');checks++;
    await page.locator('header a.logo').click();
    await page.locator('.top-in [data-a=profile]').click();
    const jokerHref=await page.locator('.pc-sheet .pc-guest').first().getAttribute('href');
    const selectedJoker=new URL(jokerHref,BASE).searchParams.get('guest');
    await page.locator('.pc-sheet .pc-advanced > summary').click();
await page.locator('.pc-sheet .pc-guest').first().click();
    await page.locator('.flow-welcome .flow-choice-solo').waitFor();checks++;
    assert.match(await page.locator('.flow-choice-solo').innerText(),/Jag kör själv/);checks++;
    await page.locator('.flow-choice-solo').click();
    session=await page.evaluate(()=>window.MOTogether.restoreSession());
    assert.equal(session.members.length,1);checks++;
    assert.equal(session.members[0],selectedJoker);checks++;
    assert.equal(session.phase,'answer','solo starts directly on question, no handoff');checks++;
    await page.locator('.options [data-action=choose]').first().click();
    await page.locator('[data-action=submit-turn]').click();
    const stats=await page.evaluate(id=>window.MOTogether.load().guests.find(g=>g.id===id).stats,selectedJoker);
    assert.ok(Object.values(stats).some(v=>v.total>=1));checks++;
    await page.locator('[data-action=next-round]').click();
    session=await page.evaluate(()=>window.MOTogether.restoreSession());
    assert.equal(session.phase,'answer','solo next question starts without another handoff');checks++;
    const stored=await page.evaluate(()=>({
      g8:JSON.parse(localStorage.getItem('matteos.v5')).profiles.grade8.rests.auditSentinel,
      g9:JSON.parse(localStorage.getItem('matteos.v5')).profiles.grade9.rests.auditSentinel,
      lang:localStorage.getItem('matteos.larande.v1'),
      pref:localStorage.getItem('matteos.together.flow.v1')
    }));
    assert.equal(stored.g8,'grade8-safe');checks++;
    assert.equal(stored.g9,'grade9-safe');checks++;
    assert.equal(stored.lang,'{"audit":"learning-safe"}');checks++;
    await page.goto(BASE+'#/cup',{waitUntil:'load'});
    await page.locator('#cup >> css=.cup-start-grid').waitFor();
    assert.equal(await page.locator('#cup >> css=.cup-start-card').count(),2);checks++;
    assert.equal(await page.locator('#cup >> css=[data-act=go][data-v=study]').count(),1);checks++;
    await page.locator('#cup >> css=[data-v=host]').click();
    assert.equal(await page.locator('#cup >> css=.cup-customize[open]').count(),0);checks++;
    assert.equal(await page.locator('#cup >> css=[data-act=cmode][data-v=quick]').getAttribute('aria-pressed'),'true');checks++;
    await page.goto(BASE+'lara/',{waitUntil:'load'});
    await page.locator('.homegrid').waitFor();
    await page.locator('button[data-a=profile]').click();
    assert.equal(await page.locator('.pc-learning-overlay .pc-grade9').count(),1);checks++;
    assert.equal(await page.locator('.pc-learning-overlay .pc-grade8').count(),1);checks++;
    assert.equal(await page.locator('.pc-learning-overlay .pc-parent').count(),1);checks++;
    assert.equal(await page.locator('.pc-learning-overlay .pc-card').count()>=6,true);checks++;
    await page.locator('.pc-learning-overlay [data-a=choose-profile][data-p=grade8]').click();
    assert.equal(await page.evaluate(()=>window.MOL_ACTIVE()),'grade8');checks++;
    assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('matteos.v5')).active),'grade8');checks++;
    await page.locator('button[data-a=profile]').click();
    await page.locator('.pc-learning-manage').click();
    await page.locator('.pc-sheet.pc-sheet').waitFor();
    assert.equal(await page.locator('.pc-sheet .pc-card').count()>=6,true);checks++;
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('.pc-sheet').count(),0);checks++;
    const width=await page.evaluate(()=>({doc:document.documentElement.scrollWidth,screen:document.documentElement.clientWidth}));
    assert(width.doc<=width.screen+2,'390px horizontal overflow '+JSON.stringify(width));checks++;
    assert.deepEqual(errors,[],'browser runtime errors');checks++;
    await context.close();
    const narrow=await browser.newContext({viewport:{width:320,height:640},isMobile:true,hasTouch:true,serviceWorkers:'block'});
    const narrowPage=await narrow.newPage();
    await narrowPage.goto(BASE,{waitUntil:'load'});
    assert.equal(await narrowPage.locator('.pc-onboarding .pc-card').count(),6);checks++;
    await narrowPage.locator('.pc-grade8').first().click();
    const narrowMeasure=await narrowPage.evaluate(()=>({doc:document.documentElement.scrollWidth,screen:document.documentElement.clientWidth}));
    assert(narrowMeasure.doc<=narrowMeasure.screen+2,'320px horizontal overflow '+JSON.stringify(narrowMeasure));checks++;
    await narrow.close();
    if(process.env.CI)console.log('FLOW QA screenshots generated by existing visual checks');
    console.log('MATTE OS ONE-TAP JOURNEYS '+engine+': '+checks+'/'+checks+' PASS — self, group, players/prefs, Joker solo, Cup, Lärande profiles, 320/390px isolation');
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
