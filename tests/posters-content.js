'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const html=read('affischer/index.html'),css=read('affischer/posters.css'),js=read('affischer/posters.js');
const root=read('index.html'),sw=read('sw.js'),core=read('js/core.js'),app=read('js/app.js');
const prov=read('prov/index.html'),provSW=read('prov/sw.js');
assert.equal((html.match(/class="formula-card"/g)||[]).length,16,'8 formula panels per year required');
assert.equal((html.match(/class="worked"/g)||[]).length>=16,true,'Every formula needs worked example');
assert(html.includes('id="poster-formler8"')&&html.includes('data-grade="8"'),'Grade-8 poster and switch required');
for(const key of ['Negativa tal','Bråk','Decimaltal','Potenser','Mått och enheter','Omkrets &amp; area','Volym','Algebra'])assert(html.includes(key),'Missing grade-8 skill '+key);
assert(html.includes('2/6 + 1/6 = 3/6 = 1/2'),'Bråk example must be correct');
assert(html.includes('0,004 = 4 · 10⁻³'),'Grade-8 powers example must be correct');
assert(html.includes('1 m² = 10 000 cm²'),'Area conversion must be correct');
assert(html.includes('V = 12π cm³ ≈ 37,7 cm³'),'Cylinder example must be correct');
assert((html.match(/class="worked"/g)||[]).length>=8,'Every formula needs worked example');
assert(html.includes('√49 = <b>7</b>')&&html.includes('x = −7'),'Principal root and equation distinction');
for(const key of ['Tiopotenser','Grundpotensform','Prefix','Potensregler','Kvadratrötter','Räkna med rötter','Division med rot','Talmängder'])assert(html.includes(key),'Missing section '+key);
assert(html.includes('a ≥ 0')&&html.includes('b &gt; 0'),'Root conditions');
assert(css.includes('repeat(4,minmax(0,1fr))')&&css.includes('max-width:720px')&&css.includes('@media print'),'Responsive and printable');
assert(js.includes('for(var n=1;n<=10;n++)')&&js.includes('for(var m=1;m<=10;m++)')&&js.includes('(n*m)'),'All 100 table values derived from multiplication');
assert(js.includes('aria-pressed')&&html.includes('aria-labelledby'),'Accessible poster selection');
assert(js.includes('document.body.dataset.grade=grade')&&js.includes('formler8'),'Grade-aware color and content');
assert(css.includes('body[data-grade="8"] .masthead')&&css.includes('#0f4e83'),'Navy poster style must exist');
assert(app.includes("pid() === 'grade8' ? '8' : '9'"),'Poster links must use pupil grade');
assert(app.includes('affischer/?visa=formler')&&app.includes('affischer/?visa=tabeller'),'Main app needs both poster entries');
assert(sw.includes('./affischer/index.html')&&sw.includes("const offlineKey = posterNav"),'Posters must have separate offline navigation cache');
assert(root.includes('5.5.1')&&sw.includes('5.5.1')&&core.includes("version: '5.5.1'"),'Core PWA cache bump');
assert(prov.includes('1.2.4')&&provSW.includes('1.2.4'),'Unchanged independent prov');
console.log('Year 8 navy/burgundy and Year 9 burgundy posters, exact arithmetic, navigation, offline and versions: PASS');
