'use strict';
/* Cross-surface safety net: all public entrypoint shells, English routes and offline versions. */
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
let n=0;const ok=(v,label)=>{assert.ok(v,label);n++};
const read=f=>fs.readFileSync(path.join(__dirname,'..',f),'utf8');
const surfaces=['index.html','study/index.html','foralder/index.html','lara/index.html','lara/speaking-lab.html','lara/debatt.html','lara/np-muntligt.html','prov/index.html','tillsammans/index.html','tillsammans/live.html','smart/index.html','studera/index.html','affischer/index.html','tabell/index.html','uppdatera.html'];
for(const name of surfaces){
 const content=read(name),rel=name.includes('/')?'../css/unified-student-ui.css?v=1.0.0':'./css/unified-student-ui.css?v=1.0.0';
 ok(content.includes(rel),'consistent accessible focus stylesheet '+name);
 ok(content.includes('<meta charset="utf-8">')||content.includes('<meta charset="utf-8"'),'valid document encoding '+name);
 ok(content.includes('</html>'),'complete document shell '+name);
}
const style=read('css/unified-student-ui.css');
ok(style.includes(':focus-visible'),'keyboard focus visible');
ok(style.includes('prefers-reduced-motion'),'reduced-motion supported');
ok(style.includes('forced-colors:active'),'high contrast OS support');
ok(!style.includes('display:none!important')&&!style.includes('visibility:hidden!important'),'global styles do not hide student content');
ok(!style.includes('background-image:url('),'no tracking pixel images');
const lang=read('lara/language-studio.js');
ok(lang.includes("gradeName(grade,lang)"),'English school year computed by locale');
ok(lang.includes('Speak Quest – play and speak'),'English direct call to action');
ok(lang.includes("'/solo'"),'direct solo game routing, no forced game setup screen');
ok(lang.includes('ls-more'),'secondary content available via disclosure');
ok(lang.includes('EN_SOLO_TALK'),'standalone oral prompts work without a partner');
ok((lang.match(/'en-[^']+':/g)||[]).length>=12,'12 original solo speaking explanations');
const shell=read('lara/app.js');
ok(shell.includes('localizeEnglishChrome'),'shared header English localization');
ok(shell.includes("document.documentElement.lang=en?'en':'sv'"),'correct document language on switch');
ok(!shell.includes('localStorage.removeItem'),'no student storage clearing added');
const speak=read('lara/speaking-play.js');
const html=read('lara/speaking-lab.html');
ok(html.includes('<html lang="en">'),'standalone English document language');
for(const t of ['Your opinion','Your reason','A real example','Keep talking','I want to speak on my own','Two views on the same question','Back to English','Give me a hint','That belongs to the other point of view'])ok(speak.includes(t),'English oral text '+t);
for(const sv of ['Nästa kort','Till mitt kort','Visa en ledtråd','Hjärnsläpp','Jag vill svara helt själv','Spela med andra'])ok(!speak.includes(sv),'no Swedish pupil-facing text '+sv);
const together=read('tillsammans/index.html');
ok(together.includes('english-context.js?v=1.0.0'),'localization included before together app');
const tc=read('tillsammans/english-context.js');
ok(tc.includes("topic==='en'"),'English only when selected');
ok(tc.includes('Submit my answer')&&tc.includes('End session'),'English game actions');
ok(!tc.includes('setItem(')&&!tc.includes('fetch('),'translation has no storage or network writes');
const debate=read('lara/debatt-app.js');
ok(debate.includes('document.documentElement.lang=ui.lang'),'debate document language follows selected game');
const root=read('sw.js'),learning=read('lara/sw.js'),exam=read('prov/sw.js');
ok(root.includes('6.12.1-20261126-ux'),'root cache version changed');
ok(learning.includes('5.6.0-english-flow'),'learning cache version changed');
ok(exam.includes('v1.3.10-20261126-ux'),'exam cache version changed');
ok(learning.includes("'../css/unified-student-ui.css'"),'offline shared stylesheet intercepted by learning worker');
ok(!learning.includes("pg?pages[pg]:'./index.html','./studio"),'no accidental multi-item cache navigation key');
ok(root.includes("tillsammans/english-context.js?v=1.0.0"),'root offline precaches English Together module');
ok(root.includes("tillsammans/app.js?v=2.2.0-english"),'root offline uses current Together code');
ok(root.includes("lara/language-studio.js?v=1.4.0-english"),'root offline uses current language code');
console.log('PLATFORM UX QA '+n+'/'+n+' PASS · '+surfaces.length+' entrypoint documents');
